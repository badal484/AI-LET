const DICTIONARIES: Record<AppLocale, Partial<Record<SocialStringKey, string>>> = { en, hi, hinglish };

export function translate(locale: AppLocale, key: SocialStringKey, params?: Record<string, string | number>): string {
  const template = DICTIONARIES[locale][key] ?? en[key];
  return params ? template.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`)) : template;
}

export function useSocialT() {
  const locale = useSettingsStore((s) => s.locale);
  return useCallback((key: SocialStringKey, params?: Record<string, string | number>) => translate(locale, key, params), [locale]);
}
